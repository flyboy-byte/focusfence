#!/usr/bin/env python3
"""Changelog from git history (roadmap Phase 6).

Squash-merged PRs titled `type(scope): summary` (AGENTS.md, "Pull requests") become one line each, grouped by type,
with the commit to `git revert` and the PR number. Older untyped commits are grouped by a simple guess.

  tools/changelog.py notes <from-ref> [<to-ref>]   # one section, for a release PR or release notes
  tools/changelog.py full                          # the whole CHANGELOG.md, every v*-accountable tag plus Unreleased

Reads git only; writes to stdout.
"""
import re
import subprocess
import sys

TYPED = re.compile(r"^(feat|fix|docs|refactor|perf|chore|test|build|ci|revert)(\(([a-z0-9-]+)\))?!?:\s*(.+)$")
GROUPS = [
    ("feat", "Added"), ("fix", "Fixed"), ("perf", "Faster or lighter"), ("refactor", "Changed"),
    ("other", "Changed"), ("docs", "Docs"), ("revert", "Reverted"), ("chore", "Maintenance"),
]
MAINT = {"test", "build", "ci", "chore"}


def git(*args):
    return subprocess.run(["git", *args], capture_output=True, text=True, check=True).stdout


def commits(rng):
    out = git("log", "--first-parent", "--format=%h%x1f%s%x1f%b%x1e", rng)
    for rec in out.split("\x1e"):
        rec = rec.strip("\n")
        if not rec:
            continue
        sha, subject, body = (rec.split("\x1f") + ["", ""])[:3]
        pr = None
        m = re.match(r"^Merge pull request #(\d+) from \S+", subject)
        if m:  # a merge commit: the PR title is the first body line
            pr = m.group(1)
            subject = next((l.strip() for l in body.splitlines() if l.strip()), subject)
        else:
            m = re.search(r"\(#(\d+)\)\s*$", subject)  # GitHub squash titles end with (#N)
            if m:
                pr, subject = m.group(1), subject[: m.start()].rstrip()
        yield sha, subject, pr


def classify(subject):
    m = TYPED.match(subject)
    if m:
        kind, scope, text = m.group(1), m.group(3), m.group(4)
        kind = "chore" if kind in MAINT else kind
        return kind, (f"**{scope}:** {text}" if scope else text)
    low = subject.lower()
    if low.startswith(("merge branch", "merge remote-tracking", "merge commit")):
        return None, None  # plumbing; merges of a PR or a whole branch into main are kept
    if re.match(r"^(fix|fixes|fixed)\b", low):
        return "fix", subject
    if low.startswith(("docs", "handoff", "state.md", "readme")):
        return "docs", subject
    return "other", subject


def section(title, rng, repo_url):
    buckets = {}
    for sha, subject, pr in commits(rng):
        kind, text = classify(subject)
        if kind is None:
            continue
        ref = f"`{sha}`" + (f", [#{pr}]({repo_url}/pull/{pr})" if pr else "")
        buckets.setdefault(kind, []).append(f"- {text} ({ref})")
    lines = [f"## {title}", ""]
    if not buckets:
        return "\n".join(lines + ["_No changes._", ""])
    seen = set()
    for kind, label in GROUPS:
        items = buckets.get(kind)
        if not items:
            continue
        if label in seen:  # "other" shares "Changed" with refactor
            lines.extend(items)
            continue
        seen.add(label)
        lines += [f"### {label}", *items]
    lines += ["", f"_Undo any line with `git revert <commit>`._", ""]
    return "\n".join(lines)


def tags():
    ts = [t for t in git("tag", "--list", "v*-accountable").split() if t]
    key = lambda t: [int(x) for x in re.findall(r"\d+", t.split("-")[0])]
    return sorted(ts, key=key)


def repo_url():
    url = git("remote", "get-url", "origin").strip()
    url = re.sub(r"^git@github\.com:", "https://github.com/", url)
    return url[:-4] if url.endswith(".git") else url


def main(argv):
    url = repo_url()
    if len(argv) >= 3 and argv[1] == "notes":
        to = argv[3] if len(argv) > 3 else "HEAD"
        print(section(f"{to} (since {argv[2]})", f"{argv[2]}..{to}", url))
    elif len(argv) == 2 and argv[1] == "full":
        ts = tags()
        out = ["# Changelog", "",
               "Generated by `tools/changelog.py full` from git history: one line per change, newest release first.",
               "Each line names the commit to `git revert` and, when there is one, the PR. Before 2.11 the history is",
               "untyped commits grouped by a guess; from then on PR titles carry the type (AGENTS.md).", ""]
        if ts:
            out.append(section("Unreleased", f"{ts[-1]}..origin/main", url))
        for i in range(len(ts) - 1, -1, -1):
            rng = f"{ts[i - 1]}..{ts[i]}" if i > 0 else ts[i]
            out.append(section(ts[i], rng, url))
        print("\n".join(out))
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
